import { afterEach, describe, expect, it, vi } from 'vitest';
import { extractTheme, fetchWeChatArticle, safeStyles, validateWeChatUrl } from '../server/extract';

const articleHtml = '<html><head><title>一篇值得阅读的文章</title><style>.chapter {color:#315c97;font-size:22px;border-bottom:1px solid #315c97}</style></head><body><div id="js_content" style="font-size:16px;line-height:1.8;color:#333333;font-family:Microsoft YaHei"><h2 class="chapter">一个清晰的章节标题</h2><p style="margin-bottom:22px">这是一段足够长的正文，用于确认主题的正文色来自大部分文字，而不是<strong style="color:#c57442">少量强调</strong>。</p><blockquote style="background-color:#edf3fa;border-left:3px solid #315c97;padding:16px">一段值得被记住的引用。</blockquote></div></body></html>';

afterEach(() => vi.unstubAllGlobals());

describe('Theme extraction', () => {
  it('extracts inline and embedded CSS without letting bold words recolor the body', () => {
    const theme = extractTheme(articleHtml, 'https://mp.weixin.qq.com/s/example');
    expect(theme.custom).toBe(true);
    expect(theme.accent).toBe('#315c97');
    expect(theme.ink).toBe('#333333');
    expect(theme.fontSize).toBe(16);
    expect(theme.lineHeight).toBe(1.8);
    expect(theme.headingStyle).toBe('underline');
    expect(theme.quoteStyle).toBe('card');
    expect(theme.styles?.h2?.['font-size']).toBe('22px');
    expect(theme.styles?.p?.['font-weight']).not.toBe('700');
    expect(theme.extraction?.detectedRoles).toContain('blockquote');
  });
  it('recognizes section/span based headings commonly generated by WeChat editors', () => {
    const theme = extractTheme('<div id="js_content" style="font-size:16px;color:#454545"><section><strong><span style="font-size:20px;color:#c57442">认真生活的小标题</span></strong></section><p><span>在忙碌的生活里，我们总要留下一些时间，用来感受身边值得被记住的片刻。</span></p></div>');
    expect(theme.styles?.h2?.['font-size']).toBe('20px');
    expect(theme.accent).toBe('#c57442');
    expect(theme.fontSize).toBe(16);
  });
  it('rejects CSS capable of requesting remote assets or breaking the article layout', () => {
    expect(safeStyles({ color: '#123456', 'background-color': 'url(https://evil.example/x)', position: 'fixed', 'font-size': '400px', 'line-height': '10000px', 'padding-left': '500px', 'margin-top': '-300px', 'font-family': 'Arial; color:red', 'border-left': '3px solid #123456' })).toEqual({ color: '#123456', 'border-left': '3px solid #123456' });
  });
  it('does not fabricate a theme from a validation or empty page', () => {
    expect(() => extractTheme('<html><body>请完成验证</body></html>')).toThrow('正文');
  });
});

describe('WeChat URL and fetch boundaries', () => {
  it.each(['http://mp.weixin.qq.com/s/test', 'https://mp.weixin.qq.com.evil.example/s/test', 'https://127.0.0.1/s/test', 'https://mp.weixin.qq.com:8443/s/test', 'https://user:pass@mp.weixin.qq.com/s/test', 'https://mp.weixin.qq.com/cgi-bin/test', 'file:///etc/passwd'])('rejects non-article or non-public targets: %s', (url) => {
    expect(() => validateWeChatUrl(url)).toThrow();
  });
  it('supports long and short WeChat article URLs', () => {
    expect(validateWeChatUrl('https://mp.weixin.qq.com/s/abc#wechat_redirect').href).toBe('https://mp.weixin.qq.com/s/abc');
    expect(validateWeChatUrl('https://mp.weixin.qq.com/s?__biz=abc&mid=12').hostname).toBe('mp.weixin.qq.com');
  });
  it('rejects redirects to local services without fetching the next hop', async () => {
    const fetchMock = vi.fn().mockResolvedValue(new Response(null, { status: 302, headers: { location: 'http://127.0.0.1:3001/api/workspace' } }));
    vi.stubGlobal('fetch', fetchMock);
    await expect(fetchWeChatArticle('https://mp.weixin.qq.com/s/test')).rejects.toMatchObject({ code: 'WECHAT_RESTRICTED' });
    expect(fetchMock).toHaveBeenCalledTimes(1);
  });
  it('reports verification pages rather than treating them as articles', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response('<html>请完成验证后继续</html>', { status: 200 })));
    await expect(fetchWeChatArticle('https://mp.weixin.qq.com/s/test')).rejects.toMatchObject({ code: 'WECHAT_RESTRICTED' });
  });
  it('reads a valid article through the bounded fetch pipeline', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response(articleHtml, { status: 200 })));
    expect((await fetchWeChatArticle('https://mp.weixin.qq.com/s/test')).html).toContain('js_content');
  });
  it('enforces a body-size limit even when content length is omitted', async () => {
    vi.stubGlobal('fetch', vi.fn().mockResolvedValue(new Response('x'.repeat(4 * 1024 * 1024 + 1), { status: 200 })));
    await expect(fetchWeChatArticle('https://mp.weixin.qq.com/s/test')).rejects.toMatchObject({ status: 413 });
  });
});
